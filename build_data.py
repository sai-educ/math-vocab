"""
Math Vocabulary Bank — K-5, Common Core aligned.

Generates vocab_data.json and vocab_bank/grade-*.md from the DATA table below.
Run this, then build_html.py:

    python3 build_data.py && python3 build_html.py

Writing guidelines for this table
---------------------------------
Definitions and examples are written for the child, not about the child, and
are checked against the Flesch scale on every build (see readability.py).

* Short sentences. Sentence length is the biggest single lever on
  readability, so two plain sentences always beat one clause-stacked one.
* Everyday words around the hard word. "denominator" is five syllables and
  cannot be avoided, but everything surrounding it can be one or two.
* Examples are *situated*: a named child, a real setting, and the reasoning
  made visible - read the problem, then work it - after Polya. The Feynman
  habit of explaining a thing in plain language is the target register.
* A small recurring cast (Maya, Leo, Ana, Ben, Ivy, Zoe, Theo, Nina, Omar,
  Sam) so the bank reads as one world instead of 189 unrelated sentences.
* Misconceptions name what a child actually does wrong, not the abstract
  error.
"""
