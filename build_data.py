def slugify(value: str) -> str:
    value = re.sub(r"[^a-z0-9]+", "-", value.lower())
    return value.strip("-")


def build_entries() -> list[dict]:
    entries = []
    for grade, domains in DATA.items():
        for dcode, terms in domains.items():
            for term, definition, example, misconception in terms:
                entries.append({
                    "id": slugify(f"{grade}-{dcode}-{term}"),
                    "term": term,
                    "grade": grade,
                    "domainCode": dcode,
                    "domain": DOMAIN_NAMES[dcode],
                    "standard": f"{grade}.{dcode}",
                    "definition": definition,
                    "example": example,
                    "misconception": misconception,
                })
    return entries


def write_markdown(out_dir: str) -> None:
    """Per-grade Markdown: the human-readable, git-friendly source of truth."""
    md_dir = os.path.join(out_dir, "vocab_bank")
    os.makedirs(md_dir, exist_ok=True)
    for grade, domains in DATA.items():
        lines = [f"# Grade {grade} Math Vocabulary\n"]
        for dcode, terms in domains.items():
            lines.append(f"\n## {DOMAIN_NAMES[dcode]} ({grade}.{dcode})\n")
            for term, definition, example, misconception in terms:
                lines.append(f"### {term}\n")
                lines.append(f"**Definition:** {definition}\n")
                lines.append(f"**Example:** {example}\n")
                if misconception:
                    lines.append(f"**Common misconception:** {misconception}\n")
        with open(os.path.join(md_dir, f"grade-{grade}.md"), "w", encoding="utf-8") as f:
            f.write("\n".join(lines))


def main() -> None:
    out_dir = os.path.dirname(os.path.abspath(__file__))
    entries = build_entries()

    ids = [e["id"] for e in entries]
    duplicates = {i for i in ids if ids.count(i) > 1}
    if duplicates:
        raise SystemExit(f"Duplicate term ids: {sorted(duplicates)}")

    with open(os.path.join(out_dir, "vocab_data.json"), "w", encoding="utf-8") as f:
        json.dump(entries, f, indent=2, ensure_ascii=False)

    write_markdown(out_dir)

    print(f"Wrote {len(entries)} terms across {len(DATA)} grades.")
    print("Markdown files written to vocab_bank/")
    readability.report(entries)


if __name__ == "__main__":
    main()
